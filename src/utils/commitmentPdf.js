// ── Refund event PDF ──────────────────────────────────────────────────────────
export function downloadRefundPDF(c, refund, txHash) {
  if (!c || !refund) return
  const base = makePdfBase(); if (!base) return
  const { doc, margin, addField, addDivider, addDisclaimer } = base
  let y = 35

  const eventLabel = refund.status === 3 ? 'Direct Refund' : `Refund ${REFUND_STATUS_LABEL[refund.status]}`

  doc.setFontSize(14); doc.setFont('helvetica', 'bold'); doc.setTextColor(17, 17, 17)
  doc.text(`${eventLabel} · ${c.ref}`, margin, y); y += 8
  doc.setFontSize(26); doc.setFont('helvetica', 'bold'); doc.setTextColor(39, 117, 202)
  doc.text(`${refund.amount} USDC`, margin, y); y += 10
  doc.setFontSize(10); doc.setFont('helvetica', 'normal'); doc.setTextColor(100, 100, 100)
  doc.text(formatTs(refund.processedAt || refund.requestedAt), margin, y); y += 8
  y = addDivider(y)

  y = addField('Event',        eventLabel, y)
  y = addField('Status',       REFUND_STATUS_LABEL[refund.status], y)
  y = addField('Ref',          refund.proofRef || c.ref, y)
  if (refund.reason) y = addField('Reason', refund.reason, y)
  y = addDivider(y)
  y = addField('Merchant',     refund.merchant || c.merchant, y)
  y = addField('Customer',     refund.customer || c.customer, y)
  y = addDivider(y)
  y = addField('Refund Amount', `${refund.amount} USDC`, y)
  y = addField('Requested At',  formatTs(refund.requestedAt), y)
  if (refund.processedAt) y = addField('Processed At', formatTs(refund.processedAt), y)
  y = addDivider(y)

  y = addField('Network',      'Arc Testnet · Chain ID 5042002', y)
  if (txHash) {
    y = addField('TX Hash',    txHash, y)
    y = addField('ArcScan',    `${ARCSCAN_BASE}/tx/${txHash}`, y)
  }
  y = addField('Receipt URL',  `${APP_URL}/commitment/${c.commitmentId}`, y)

  addDisclaimer(270)
  doc.save(`arcpay_refund_${(c.ref || c.commitmentId).replace(/[^a-zA-Z0-9-_]/g, '_')}.pdf`)
}
